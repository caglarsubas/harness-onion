def test_the_models_are_executed_from_this_eras_bytes_with_the_era_import_closure(monkeypatch):
    built = []
    original = profile._era_model

    def era_model(path, name, imports=None):
        module = original(path, name, imports)
        built.append((path, name, imports, module))
        return module
    monkeypatch.setattr(profile, "_era_model", era_model)
    a1, a2 = profile.era_modules()
    assert [(path, name) for path, name, _, _ in built] == [
        (profile.SAFE_YAML, "_met_enforce_031_safe_yaml"), (profile.A1_MODEL, "_met_enforce_031_license_amendment"),
        (profile.A2_MODEL, "_met_enforce_031_license_amendment_v2")]
    safe_yaml = built[0][3]
    # LR3-2: A1's import closure is this era's safe_yaml, executed from its verified bytes.
    assert built[1][2]["safe_yaml"] is built[1][2]["scripts.safe_yaml"] is safe_yaml
    assert a1.SafeLoader is safe_yaml.SafeLoader and a1.__dict__["__builtins__"]["__import__"] is not __import__
    assert built[2][2]["license_amendment"] is a1 and a2.a1 is a1 and a2.classify is a1.classify
    assert a2.Path.__module__ != "pathlib" and a2.Path.__qualname__.endswith("EraPath")
    assert a2.check(profile._verified)["amendmentId"] == "LIC-HOST-A2"


