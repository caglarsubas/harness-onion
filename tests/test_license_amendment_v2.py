def _weakened(term, outcome):
    a1, _ = profile.era_modules()
    good = a1.classify

    def classify(policy, expression, component):
        return {"outcome": outcome, "elections": []} if expression == term else good(policy, expression, component)
    return types.SimpleNamespace(classify=classify), a1


