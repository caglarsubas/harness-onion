def test_the_conftest_wrapper_shares_only_within_its_own_test():
    conftest = _conftest_module()
    calls = []

    def real(path, raw):
        calls.append((path, raw))
        if raw == b"refuse":
            raise ValueError("refused")
        return raw + b"!"

    memo = {}
    wrapper = conftest._shared(real, memo)
    assert conftest._is_wrapper(wrapper) and wrapper.__wrapped__ is real
    conftest._ACTIVE["memo"] = memo
    try:
        assert wrapper("p", b"x") == wrapper("p", b"x") == b"x!" and len(calls) == 1
        assert wrapper("p", bytearray(b"x")) == b"x!" and len(calls) == 2        # only str and bytes are shared
        assert wrapper("p", raw=b"x") == b"x!" and len(calls) == 3               # keywords pass through
        for _ in range(2):
            with pytest.raises(ValueError, match="refused"):
                wrapper("p", b"refuse")
        assert len(calls) == 5                                                    # refusals are never memoised
        conftest._ACTIVE["memo"] = {}                                             # another test's memo
        assert wrapper("p", b"x") == b"x!" and len(calls) == 6
    finally:
        conftest._ACTIVE["memo"] = None
    assert wrapper("p", b"x") == b"x!" and len(calls) == 7                        # inert outside tests
    assert conftest._unwrap(conftest._shared(wrapper, memo)) is real


